// Regenerates src/common-passwords.ts from the SecLists 10k list:
//   curl -fsSL https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/10k-most-common.txt -o /tmp/10k.txt
//   node scripts/generate-common-passwords.mjs /tmp/10k.txt
// Only entries of at least PASSWORD_MIN_LENGTH characters are kept: shorter
// ones already fail the length rule, and dropping them keeps the module small.
import { readFileSync, writeFileSync } from 'node:fs';

const MIN_LENGTH = 8;
const [input] = process.argv.slice(2);
if (input === undefined)
  throw new Error('usage: generate-common-passwords.mjs <10k-most-common.txt>');

const words = [
  ...new Set(
    readFileSync(input, 'utf8')
      .split(/\r?\n/)
      .map((word) => word.trim().toLowerCase())
      .filter((word) => [...word].length >= MIN_LENGTH),
  ),
].sort();

const source = `// Generated by scripts/generate-common-passwords.mjs. Do not edit by hand.
// Source: SecLists Passwords/Common-Credentials/10k-most-common.txt
// Copyright (c) 2018 Daniel Miessler, MIT License (see THIRD_PARTY_NOTICES.md).
// ${words.length} entries of at least ${MIN_LENGTH} characters, lower-cased.

const WORDS = ${JSON.stringify(words.join('\n'))};

/** Top common passwords (lower-cased). Import lazily in the browser: it is ~23 kB. */
const commonPasswords: ReadonlySet<string> = new Set(WORDS.split('\\n'));

export default commonPasswords;

/** Case-insensitive membership test for the password policy's COMMON rule. */
export function isCommonPassword(password: string): boolean {
  return commonPasswords.has(password.toLowerCase());
}
`;
writeFileSync(new URL('../src/common-passwords.ts', import.meta.url), source);
process.stdout.write(`wrote ${words.length} passwords\n`);
