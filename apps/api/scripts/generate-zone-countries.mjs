// Regenerates src/modules/meta/infra/zone-countries.ts from the IANA tz database:
//   curl -fsSL https://raw.githubusercontent.com/eggert/tz/main/zone.tab -o /tmp/zone.tab
//   node scripts/generate-zone-countries.mjs /tmp/zone.tab
// zone.tab (public domain) lists each geographic zone once with its country code.
import { readFileSync, writeFileSync } from 'node:fs';

const [input] = process.argv.slice(2);
if (input === undefined) throw new Error('usage: generate-zone-countries.mjs <zone.tab>');

const entries = readFileSync(input, 'utf8')
  .split('\n')
  .filter((line) => line.trim() !== '' && !line.startsWith('#'))
  .map((line) => line.split('\t'))
  .map(([country, , zone]) => [zone, country])
  .sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([zone, country]) => `  '${zone}': '${country}',`).join('\n');
const source = `// Generated by scripts/generate-zone-countries.mjs from the IANA tz database zone.tab
// (public domain). Do not edit by hand.

/** Geographic IANA zones and their ISO 3166 country code. */
export const ZONE_COUNTRIES: Readonly<Record<string, string>> = {
${body}
};
`;
writeFileSync(new URL('../src/modules/meta/infra/zone-countries.ts', import.meta.url), source);
process.stdout.write(`wrote ${entries.length} zones\n`);
